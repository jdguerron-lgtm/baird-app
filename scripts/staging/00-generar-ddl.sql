-- Kit de staging — genera el DDL completo del schema `public` de PRODUCCIÓN leyendo el catálogo.
-- SOLO LECTURA (solo SELECT). Reemplaza a `pg_dump --schema-only` cuando no hay cliente de
-- PostgreSQL instalado. Se corre en prod (SQL Editor o MCP execute_sql) y su salida —una fila
-- por sentencia, en orden— se aplica tal cual en staging.
--
-- Cubre: extensiones usadas, secuencias, tablas (tipos, defaults, NOT NULL, identity, generadas),
-- propiedad de secuencias, PK/UNIQUE/CHECK (incluido NOT VALID), FKs, índices sueltos, funciones,
-- triggers, RLS, policies de `public`, grants de EXECUTE no por defecto y comentarios de tablas.
-- NO cubre (a propósito): datos, Storage (→ 01-storage-buckets-y-policies.sql), Vault, jobs de
-- pg_cron (apuntan a la URL de prod) ni Auth.
--
-- Verificación después de aplicar: 02-inventario-schema.sql en prod y en staging → diff vacío.

with
tablas as (
  select c.oid, c.relname, c.relrowsecurity, c.relforcerowsecurity
  from pg_class c
  where c.relnamespace = 'public'::regnamespace and c.relkind = 'r'
),
ext as (
  select 0 as fase, e.extname as clave,
         format('create extension if not exists %I with schema %I;', e.extname, n.nspname) as ddl
  from pg_extension e join pg_namespace n on n.oid = e.extnamespace
  where e.extname in ('pgcrypto', 'uuid-ossp', 'pg_cron', 'pg_net')
),
seqs as (
  select 1, s.relname,
         format('create sequence if not exists public.%I as %s;', s.relname, format_type(q.seqtypid, null))
  from pg_class s join pg_sequence q on q.seqrelid = s.oid
  where s.relnamespace = 'public'::regnamespace and s.relkind = 'S'
    and not exists (            -- las de columnas identity las crea la propia columna
      select 1 from pg_depend d where d.objid = s.oid and d.deptype = 'i')
),
cols as (
  select 2, t.relname,
         format(E'create table if not exists public.%I (\n%s\n);', t.relname,
           string_agg(
             '  ' || quote_ident(a.attname) || ' ' || format_type(a.atttypid, a.atttypmod)
             || case a.attidentity when 'a' then ' generated always as identity'
                                   when 'd' then ' generated by default as identity' else '' end
             || case when a.attgenerated = 's' then ' generated always as (' || pg_get_expr(ad.adbin, ad.adrelid) || ') stored'
                     when ad.adbin is not null and a.attidentity = '' then ' default ' || pg_get_expr(ad.adbin, ad.adrelid)
                     else '' end
             || case when a.attnotnull then ' not null' else '' end,
             E',\n' order by a.attnum))
  from tablas t
  join pg_attribute a on a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped
  left join pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
  group by t.relname
),
owned as (
  select 3, s.relname,
         format('alter sequence public.%I owned by public.%I.%I;', s.relname, t.relname, a.attname)
  from pg_class s
  join pg_depend d on d.objid = s.oid and d.deptype = 'a' and d.classid = 'pg_class'::regclass
  join pg_class t on t.oid = d.refobjid
  join pg_attribute a on a.attrelid = t.oid and a.attnum = d.refobjsubid
  where s.relkind = 'S' and s.relnamespace = 'public'::regnamespace
),
cons as (
  select case when co.contype = 'f' then 5 else 4 end,
         t.relname || '.' || co.conname,
         format('alter table public.%I add constraint %I %s;', t.relname, co.conname, pg_get_constraintdef(co.oid))
  from pg_constraint co join tablas t on t.oid = co.conrelid
  where co.contype in ('p', 'u', 'c', 'f', 'x')
),
idx as (
  select 6, i.indexrelid::regclass::text, pg_get_indexdef(i.indexrelid) || ';'
  from pg_index i join tablas t on t.oid = i.indrelid
  where not exists (select 1 from pg_constraint co where co.conindid = i.indexrelid)
),
fns as (
  select 7, p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')',
         pg_get_functiondef(p.oid) || ';'
  from pg_proc p
  where p.pronamespace = 'public'::regnamespace and p.prokind = 'f'
),
trg as (
  select 8, t.relname || '.' || g.tgname, pg_get_triggerdef(g.oid) || ';'
  from pg_trigger g join tablas t on t.oid = g.tgrelid
  where not g.tgisinternal
),
rls as (
  select 9, relname, format('alter table public.%I enable row level security;', relname)
  from tablas where relrowsecurity
  union all
  select 9, relname || '+force', format('alter table public.%I force row level security;', relname)
  from tablas where relforcerowsecurity
),
pol as (
  select 10, p.tablename || '.' || p.policyname,
         format('create policy %I on public.%I as %s for %s to %s%s%s;',
           p.policyname, p.tablename, lower(p.permissive), p.cmd,
           (select string_agg(case when r = 'public' then 'public' else quote_ident(r) end, ', ') from unnest(p.roles) r),
           case when p.qual is not null then ' using (' || p.qual || ')' else '' end,
           case when p.with_check is not null then ' with check (' || p.with_check || ')' else '' end)
  from pg_policies p
  where p.schemaname = 'public'
),
grants as (
  -- Funciones a las que se les quitó el EXECUTE público (hardening 2026-10-24) → replicar.
  select 11, p.proname,
         format('revoke execute on function public.%I(%s) from public, anon, authenticated; grant execute on function public.%I(%s) to service_role;',
           p.proname, pg_get_function_identity_arguments(p.oid), p.proname, pg_get_function_identity_arguments(p.oid))
  from pg_proc p
  where p.pronamespace = 'public'::regnamespace and p.prokind = 'f'
    and not has_function_privilege('anon', p.oid, 'execute')
),
coms as (
  select 12, t.relname, format('comment on table public.%I is %L;', t.relname, obj_description(t.oid, 'pg_class'))
  from tablas t where obj_description(t.oid, 'pg_class') is not null
)
select fase, clave, ddl from (
  select * from ext   union all select * from seqs  union all select * from cols  union all
  select * from owned union all select * from cons  union all select * from idx   union all
  select * from fns   union all select * from trg   union all select * from rls   union all
  select * from pol   union all select * from grants union all select * from coms
) x
order by fase, clave;
